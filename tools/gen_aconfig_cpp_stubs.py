#!/usr/bin/env python3
"""Generate minimal C++ aconfig flag libraries from AOSP .aconfig files.

The real build uses the `aconfig` tool (written in Rust) to turn these files
into C++/Java libraries.  That tool is part of platform/build, which this
standalone tree intentionally does not clone.  For a host-only ART build we
only need the getters, so generate a small, deterministic implementation.

Every flag defaults to false.  That is the safe/non-experimental behaviour for
ART's feature flags and keeps the build independent of an Android device config.
"""

from pathlib import Path
import re
import sys

FLAG_RE = re.compile(r'flag\s*\{(.*?)\n\}', re.S)
NAME_RE = re.compile(r'name:\s*"([^"]+)"')


def parse(text):
    names = []
    for block in FLAG_RE.findall(text):
        m = NAME_RE.search(block)
        if m:
            names.append(m.group(1))
    return names


def main():
    in_path = sys.argv[1]
    package = sys.argv[2]
    impl = []
    impl.append('// Generated by tools/gen_aconfig_stubs.py -- do not edit.\n')
    impl.append('#include <cstddef>\n')

    names = parse(Path(in_path).read_text())
    cpp_ns = package.split(".")
    ns_open = "".join(f"namespace {p} {{ " for p in cpp_ns)
    ns_close = "} " * len(cpp_ns)

    cprefix = package.replace('.', '_')

    lines = ["// Generated by tools/gen_aconfig_stubs.py -- do not edit.",
             "#pragma once", ""]
    lines.append(f"#define {cprefix.upper()}(FLAG) {cprefix.upper()}_##FLAG")
    for name in names:
        lines.append(f"#define {cprefix.upper()}_{name.upper()} false")
    lines.append("")
    # aconfig also emits flat C entry points used by a few ART files.
    for name in names:
        lines.append(f"constexpr bool {cprefix}_{name}() {{ return false; }}")
    lines.append("")
    lines.append(ns_open)
    for name in names:
        lines.append(f"constexpr bool {name}() {{ return false; }}")
    lines.append(ns_close)
    lines.append("")
    print('\n'.join(lines))

if __name__ == "__main__":
    sys.exit(main())
