#!/usr/bin/env python3
"""Generate Java aconfig flag classes from AOSP .aconfig files.

The platform build uses the Rust `aconfig` tool to turn these declarations into
Java libraries.  That tool is not part of this tree, and the generated classes
are tiny, so parse the declarations and emit equivalent sources.  Every flag
reads as `false`, the safe/non-experimental value on a host without a device
config.
"""

from pathlib import Path
import re
import sys

PACKAGE_RE = re.compile(r'^\s*package:\s*"([^"]+)"', re.M)
FLAG_BLOCK_RE = re.compile(r'(?m)^\s*flag\s*\{(.*?)^\s*\}', re.S)
NAME_RE = re.compile(r'^\s*name:\s*"([^"]+)"', re.M)


def parse(text):
    m = PACKAGE_RE.search(text)
    if not m:
        return None, []
    # A flag block always declares exactly one `name`; only accept names that
    # actually appear inside a top-level flag block.
    names = []
    for block in FLAG_BLOCK_RE.findall(text):
        n = NAME_RE.search(block)
        if n:
            names.append(n.group(1))
    return m.group(1), names


def camel(name):
    parts = name.split("_")
    return parts[0] + "".join(p.capitalize() for p in parts[1:])


def main():
    in_path = sys.argv[1]
    package, names = parse(Path(in_path).read_text())

    lines = [
        "// Generated by tools/gen_aconfig_java.py -- do not edit.",
        f"package {package};",
        "",
        "public final class Flags {",
        "    private Flags() {}",
        "",
    ]
    for name in names:
        const = "FLAG_" + name.upper()
        lines.append(f'    public static final String {const} = "{name}";')
    lines.append("")
    for name in names:
        lines.append(f"    public static boolean {camel(name)}() {{ return false; }}")
    lines.append("}")
    print("\n".join(lines))

if __name__ == "__main__":
    sys.exit(main())
